//! `laysi-schema`: generate the frontend TypeScript from the operation
//! registry.
//!
//! ```sh
//! cargo run -p laysi-server --bin laysi-schema -- ../web/src/api/generated.ts
//! ```
//!
//! This is the third outlet of the single source of truth: the REST routes,
//! the MCP `tools/list` and these TypeScript types all come from one
//! [`laysi_ops::Registry`]. The frontend never copies operation names, so it
//! cannot copy them wrongly or miss one.

use laysi_ops::Registry;

fn main() -> std::io::Result<()> {
    let out = std::env::args().nth(1);
    let registry = Registry::new();

    let mut ts = String::new();
    ts.push_str(
        "// Generated by `cargo run -p laysi-server --bin laysi-schema`. Do not edit.\n\
         // Operations are defined only in backend/crates/laysi-ops/src/lib.rs.\n\n",
    );

    ts.push_str("export type OpName =\n");
    for op in registry.iter() {
        ts.push_str(&format!("  | '{}'\n", op.name()));
    }
    ts.push_str(";\n\n");

    // Derived from the enum, not spelled out here: a hand-written union drifts
    // the moment a tier is added.
    let risks: Vec<String> = laysi_ops::Risk::ALL
        .iter()
        .map(|r| format!("'{}'", r.as_db()))
        .collect();
    ts.push_str(&format!(
        "export const RISKS = [{}] as const;\nexport type Risk = (typeof RISKS)[number];\n\n",
        risks.join(", ")
    ));

    ts.push_str(
        "export interface OpMeta {\n  name: OpName;\n  risk: Risk;\n  \
         riskLabel: string;\n  summary: string;\n}\n\n",
    );
    ts.push_str("export const OPS: readonly OpMeta[] = [\n");
    for op in registry.iter() {
        ts.push_str(&format!(
            "  {{ name: '{}', risk: '{}', riskLabel: '{}', summary: {} }},\n",
            op.name(),
            op.risk().as_db(),
            op.risk().label_zh(),
            serde_json::to_string(op.summary()).unwrap_or_else(|_| "''".into()),
        ));
    }
    ts.push_str("] as const;\n\n");

    ts.push_str("/** 每個操作的輸入 JSON Schema，可供表單產生或執行期驗證使用。 */\n");
    ts.push_str("export const INPUT_SCHEMAS: Record<OpName, unknown> = {\n");
    for op in registry.iter() {
        ts.push_str(&format!(
            "  '{}': {},\n",
            op.name(),
            serde_json::to_string(&op.input_schema()).unwrap_or_else(|_| "{}".into()),
        ));
    }
    ts.push_str("};\n");

    match out {
        Some(path) => {
            std::fs::write(&path, &ts)?;
            eprintln!("wrote {path} ({} operations)", registry.len());
        }
        None => print!("{ts}"),
    }
    Ok(())
}
